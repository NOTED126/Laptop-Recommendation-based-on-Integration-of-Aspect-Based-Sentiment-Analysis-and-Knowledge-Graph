def create_entity_edges(specs, laptops, brands, processors, gpus, os_nodes):
    laptop_lookup = dict(zip(laptops["product_name"], laptops["laptop_id"]))
    brand_lookup = dict(zip(brands["brand_name"], brands["brand_id"]))
    os_lookup = dict(zip(os_nodes["os_name"], os_nodes["os_id"]))

    processor_lookup = {}
    gpu_lookup = {}

    for _, row in specs.iterrows():
        processor_key = (
            clean_text(row.get("Processor Brand")),
            clean_text(row.get("Processor Model")),
            clean_text(row.get("Processor Model Number")),
        )
        processor_lookup[processor_key] = stable_id("cpu", *processor_key)

        gpu_key = (
            clean_text(row.get("GPU Brand")),
            clean_text(row.get("Graphics")),
        )
        gpu_lookup[gpu_key] = stable_id("gpu", *gpu_key)

    brand_edges = []
    processor_edges = []
    gpu_edges = []
    os_edges = []

    for _, row in specs.iterrows():
        product_name = clean_text(row["Product Name"])
        laptop_id = laptop_lookup[product_name]

        brand = clean_text(row.get("Brand"))
        brand_edges.append(
            {
                "laptop_id": laptop_id,
                "brand_id": brand_lookup[brand],
            }
        )

        processor_key = (
            clean_text(row.get("Processor Brand")),
            clean_text(row.get("Processor Model")),
            clean_text(row.get("Processor Model Number")),
        )
        processor_edges.append(
            {
                "laptop_id": laptop_id,
                "processor_id": processor_lookup[processor_key],
            }
        )

        gpu_key = (
            clean_text(row.get("GPU Brand")),
            clean_text(row.get("Graphics")),
        )
        gpu_edges.append(
            {
                "laptop_id": laptop_id,
                "gpu_id": gpu_lookup[gpu_key],
            }
        )

        os_name = clean_text(row.get("Operating System"))
        os_edges.append(
            {
                "laptop_id": laptop_id,
                "os_id": os_lookup[os_name],
            }
        )

    return (
        pd.DataFrame(brand_edges),
        pd.DataFrame(processor_edges),
        pd.DataFrame(gpu_edges),
        pd.DataFrame(os_edges),
    )


def create_aspect_score_edges(scores, laptops):
    laptop_lookup = dict(zip(laptops["product_name"], laptops["laptop_id"]))

    rows = []

    for _, row in scores.iterrows():
        laptop_name = clean_text(row["laptop"])

        rows.append(
            {
                "laptop_id": laptop_lookup[laptop_name],
                "aspect_id": clean_text(row["canonical_aspect"]),

                "positive_reviews": integer_number(row.get("positive_reviews")),
                "negative_reviews": integer_number(row.get("negative_reviews")),
                "neutral_reviews": integer_number(row.get("neutral_reviews")),
                "mixed_reviews": integer_number(row.get("mixed_reviews")),
                "mention_count": integer_number(
                    row.get("reviews_mentioning_aspect")
                ),

                "positive_ratio": row.get("positive_ratio"),
                "raw_sentiment_score": row.get("raw_sentiment_score"),
                "raw_sentiment_score_0_100": row.get(
                    "raw_sentiment_score_0_100"
                ),

                "prior_score": row.get("prior_score"),
                "prior_score_0_100": row.get("prior_score_0_100"),

                "adjusted_score": row.get("adjusted_score"),
                "adjusted_score_0_100": row.get("adjusted_score_0_100"),

                "evidence_confidence": row.get("evidence_confidence"),
                "evidence_confidence_0_100": row.get(
                    "evidence_confidence_0_100"
                ),
                "evidence_level": clean_text(row.get("evidence_level")),
                "has_direct_evidence": row.get("has_direct_evidence"),
            }
        )

    edges = pd.DataFrame(rows)

    if edges.duplicated(["laptop_id", "aspect_id"]).any():
        raise ValueError(
            "Duplicate laptop-aspect relationships were generated."
        )

    return edges


