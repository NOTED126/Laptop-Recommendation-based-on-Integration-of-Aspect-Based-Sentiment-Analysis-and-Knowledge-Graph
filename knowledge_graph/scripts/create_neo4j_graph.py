def scalar_for_neo4j(value):
    """Convert pandas/numpy scalar values to Neo4j-safe Python scalars."""
    if value is None:
        return None

    try:
        if pd.isna(value):
            return None
    except (TypeError, ValueError):
        pass

    # numpy scalar -> regular Python scalar
    if hasattr(value, "item"):
        try:
            value = value.item()
        except Exception:
            pass

    if isinstance(value, float):
        if math.isnan(value) or math.isinf(value):
            return None

    # CSV boolean values may be read as strings in mixed columns.
    if isinstance(value, str):
        stripped = value.strip()
        lowered = stripped.lower()

        if lowered == "true":
            return True
        if lowered == "false":
            return False
        if lowered in {"", "nan", "none", "null"}:
            return None

        return stripped

    return value


def dataframe_records(path):
    """Load a CSV and return Neo4j-safe row dictionaries."""
    df = pd.read_csv(path)

    records = []
    for row in df.to_dict(orient="records"):
        clean = {
            key: scalar_for_neo4j(value)
            for key, value in row.items()
        }
        records.append(clean)

    return records


def batches(rows, batch_size):
    for start in range(0, len(rows), batch_size):
        yield rows[start:start + batch_size]


def create_driver(uri, username, password):
    driver = GraphDatabase.driver(
        uri,
        auth=(username, password),
    )
    driver.verify_connectivity()
    return driver


def clear_database(session):
    print("\nWARNING: --clear-existing was supplied.")
    print("Deleting every node and relationship in the target database...")
    session.run("MATCH (n) DETACH DELETE n").consume()
    print("Target database cleared.")


def create_constraints(session):
    print("\nCreating/verifying uniqueness constraints...")
    for name, query in CONSTRAINTS:
        session.run(query).consume()
        print(f"  {name}: OK")


def import_nodes(session, data_dir, batch_size):
    print("\nImporting nodes...")

    totals = {}

    for item in NODE_IMPORTS:
        path = data_dir / item["filename"]
        if not path.exists():
            raise FileNotFoundError(f"Required KG data file missing: {path}")

        rows = dataframe_records(path)
        label = item["label"]
        id_column = item["id_column"]

        if any(row.get(id_column) is None for row in rows):
            raise ValueError(
                f"{path.name} contains a row with a missing {id_column}."
            )

        query = (
            f"UNWIND $rows AS row "
            f"MERGE (n:{label} {{{id_column}: row.{id_column}}}) "
            f"SET n += row"
        )

        imported = 0
        for batch in batches(rows, batch_size):
            session.run(query, rows=batch).consume()
            imported += len(batch)

        totals[label] = imported
        print(f"  {label:<18} {imported:>5} source rows")

    return totals


def relationship_rows(path, source_id_column, target_id_column):
    """
    Convert an edge CSV into:
        {
            source_id: ...,
            target_id: ...,
            props: {...relationship properties...}
        }
    """
    raw_rows = dataframe_records(path)
    converted = []

    for row in raw_rows:
        source_id = row.get(source_id_column)
        target_id = row.get(target_id_column)

        if source_id is None or target_id is None:
            raise ValueError(
                f"{path.name} contains a relationship with a missing endpoint ID."
            )

        props = {
            key: value
            for key, value in row.items()
            if key not in {source_id_column, target_id_column}
            and value is not None
        }

        converted.append(
            {
                "source_id": source_id,
                "target_id": target_id,
                "props": props,
            }
        )

    return converted


def import_relationships(session, data_dir, batch_size):
    print("\nImporting relationships...")

    totals = {}

    for item in RELATIONSHIP_IMPORTS:
        path = data_dir / item["filename"]
        if not path.exists():
            raise FileNotFoundError(f"Required KG data file missing: {path}")

        rows = relationship_rows(
            path=path,
            source_id_column=item["source_id_column"],
            target_id_column=item["target_id_column"],
        )

        source_label = item["source_label"]
        source_id_column = item["source_id_column"]
        target_label = item["target_label"]
        target_id_column = item["target_id_column"]
        rel_type = item["relationship_type"]

        query = (
            f"UNWIND $rows AS row "
            f"MATCH (source:{source_label} "
            f"{{{source_id_column}: row.source_id}}) "
            f"MATCH (target:{target_label} "
            f"{{{target_id_column}: row.target_id}}) "
            f"MERGE (source)-[r:{rel_type}]->(target) "
            f"SET r += row.props"
        )

        imported = 0
        for batch in batches(rows, batch_size):
            result = session.run(query, rows=batch)
            summary = result.consume()

            # If endpoint MATCHes fail, fewer relationships are created/matched
            # than the source rows. Verification below catches that globally.
            imported += len(batch)

        totals[rel_type] = imported
        print(f"  {rel_type:<22} {imported:>5} source rows")

    return totals


def load_manifest(data_dir):
    path = data_dir / "kg_manifest.json"
    if not path.exists():
        return None

    return json.loads(path.read_text(encoding="utf-8"))


def actual_graph_counts(session):
    node_queries = {
        "Laptop": "MATCH (n:Laptop) RETURN count(n) AS count",
        "Brand": "MATCH (n:Brand) RETURN count(n) AS count",
        "Processor": "MATCH (n:Processor) RETURN count(n) AS count",
        "GPU": "MATCH (n:GPU) RETURN count(n) AS count",
        "OperatingSystem": (
            "MATCH (n:OperatingSystem) RETURN count(n) AS count"
        ),
        "Aspect": "MATCH (n:Aspect) RETURN count(n) AS count",
    }

    relationship_types = [
        "MADE_BY",
        "HAS_PROCESSOR",
        "HAS_GPU",
        "RUNS_OS",
        "HAS_ASPECT_SCORE",
    ]

    nodes = {}
    for label, query in node_queries.items():
        nodes[label] = session.run(query).single()["count"]

    relationships = {}
    for rel_type in relationship_types:
        query = f"MATCH ()-[r:{rel_type}]->() RETURN count(r) AS count"
        relationships[rel_type] = session.run(query).single()["count"]

    return {
        "nodes": nodes,
        "relationships": relationships,
    }


def verify_endpoint_integrity(session):
    """
    Check the graph shape expected by the thesis.

    Each laptop should have exactly one Brand, Processor, GPU and OS relation.
    Each laptop should also have the full set of aspect score relationships.
    """
    queries = {
        "laptops_without_brand": """
            MATCH (l:Laptop)
            WHERE NOT (l)-[:MADE_BY]->(:Brand)
            RETURN count(l) AS count
        """,
        "laptops_without_processor": """
            MATCH (l:Laptop)
            WHERE NOT (l)-[:HAS_PROCESSOR]->(:Processor)
            RETURN count(l) AS count
        """,
        "laptops_without_gpu": """
            MATCH (l:Laptop)
            WHERE NOT (l)-[:HAS_GPU]->(:GPU)
            RETURN count(l) AS count
        """,
        "laptops_without_os": """
            MATCH (l:Laptop)
            WHERE NOT (l)-[:RUNS_OS]->(:OperatingSystem)
            RETURN count(l) AS count
        """,
    }

    output = {}
    for name, query in queries.items():
        output[name] = session.run(query).single()["count"]

    aspect_count = session.run(
        "MATCH (a:Aspect) RETURN count(a) AS count"
    ).single()["count"]

    incomplete_aspect_matrix = session.run(
        """
        MATCH (l:Laptop)
        OPTIONAL MATCH (l)-[r:HAS_ASPECT_SCORE]->(:Aspect)
        WITH l, count(r) AS score_count, $aspect_count AS aspect_count
        WHERE score_count <> aspect_count
        RETURN count(l) AS count
        """,
        aspect_count=aspect_count,
    ).single()["count"]

    output["laptops_with_incomplete_aspect_matrix"] = incomplete_aspect_matrix
    return output


def verify_against_manifest(session, manifest):
    actual = actual_graph_counts(session)

    if manifest is None:
        print("\nNo kg_manifest.json found; reporting actual graph counts only.")
        return True, actual, {}

    mismatches = {}

    for label, expected in manifest.get("nodes", {}).items():
        actual_count = actual["nodes"].get(label)
        if actual_count != expected:
            mismatches[f"node:{label}"] = {
                "expected": expected,
                "actual": actual_count,
            }

    for rel_type, expected in manifest.get("relationships", {}).items():
        actual_count = actual["relationships"].get(rel_type)
        if actual_count != expected:
            mismatches[f"relationship:{rel_type}"] = {
                "expected": expected,
                "actual": actual_count,
            }

    return not mismatches, actual, mismatches


def print_verification(actual, integrity, mismatches):
    print("\n" + "=" * 72)
    print("NEO4J GRAPH VERIFICATION")
    print("=" * 72)

    print("\nNodes:")
    for label, count in actual["nodes"].items():
        print(f"  {label:<18} {count:>5}")

    print("\nRelationships:")
    for rel_type, count in actual["relationships"].items():
        print(f"  {rel_type:<22} {count:>5}")

    print("\nEndpoint integrity:")
    integrity_ok = True
    for name, count in integrity.items():
        status = "PASS" if count == 0 else "FAIL"
        if count != 0:
            integrity_ok = False
        print(f"  {name:<42} {count:>5}  {status}")

    if mismatches:
        print("\nManifest count mismatches:")
        for name, detail in mismatches.items():
            print(
                f"  {name}: expected={detail['expected']} "
                f"actual={detail['actual']}"
            )

    print("\nResult:")
    if not mismatches and integrity_ok:
        print("  PASS - graph matches the prepared KG data.")
    else:
        print("  FAIL - inspect the mismatches above before proceeding.")

    print("=" * 72)

    return (not mismatches) and integrity_ok


def parse_args():
    parser = argparse.ArgumentParser(
        description=(
            "Import the prepared thesis knowledge graph into Neo4j "
            "(local Neo4j or AuraDB)."
        )
    )

    parser.add_argument(
        "--data-dir",
        default="knowledge_graph/data",
        help="Directory produced by prepare_kg_data.py.",
    )
    parser.add_argument(
        "--uri",
        default=os.getenv("NEO4J_URI", "bolt://localhost:7687"),
        help=(
            "Neo4j URI. Defaults to NEO4J_URI or bolt://localhost:7687."
        ),
    )
    parser.add_argument(
        "--username",
        default=os.getenv("NEO4J_USERNAME", "neo4j"),
        help="Neo4j username. Defaults to NEO4J_USERNAME or neo4j.",
    )
    parser.add_argument(
        "--password",
        default=os.getenv("NEO4J_PASSWORD"),
        help=(
            "Neo4j password. Prefer NEO4J_PASSWORD instead of CLI input "
            "so the password is not stored in shell history."
        ),
    )
    parser.add_argument(
        "--database",
        default=os.getenv("NEO4J_DATABASE", "neo4j"),
        help="Database name. Defaults to NEO4J_DATABASE or neo4j.",
    )
    parser.add_argument(
        "--batch-size",
        type=int,
        default=500,
        help="Rows per UNWIND transaction (default: 500).",
    )
    parser.add_argument(
        "--clear-existing",
        action="store_true",
        help=(
            "DANGEROUS: delete every existing node/relationship in the "
            "target database before importing."
        ),
    )

    return parser.parse_args()


def main():
    args = parse_args()

    if not args.password:
        raise ValueError(
            "Neo4j password was not provided. Set NEO4J_PASSWORD "
            "or supply --password."
        )

    data_dir = Path(args.data_dir)
    if not data_dir.exists():
        raise FileNotFoundError(f"KG data directory not found: {data_dir}")

    print("=" * 72)
    print("THESIS NEO4J GRAPH IMPORT")
    print("=" * 72)
    print(f"URI:       {args.uri}")
    print(f"Database:  {args.database}")
    print(f"Data dir:  {data_dir}")
    print(f"Batch size:{args.batch_size:>8}")

    manifest = load_manifest(data_dir)

    driver = create_driver(
        uri=args.uri,
        username=args.username,
        password=args.password,
    )

    try:
        with driver.session(database=args.database) as session:
            if args.clear_existing:
                clear_database(session)

            create_constraints(session)
            import_nodes(session, data_dir, args.batch_size)
            import_relationships(session, data_dir, args.batch_size)

            manifest_ok, actual, mismatches = verify_against_manifest(
                session,
                manifest,
            )

            integrity = verify_endpoint_integrity(session)
            success = print_verification(
                actual=actual,
                integrity=integrity,
                mismatches=mismatches,
            )

            if not success:
                raise RuntimeError(
                    "Neo4j import completed but graph verification failed."
                )

    finally:
        driver.close()

    print("\nNeo4j knowledge graph import completed successfully.")


if __name__ == "__main__":
    main()
