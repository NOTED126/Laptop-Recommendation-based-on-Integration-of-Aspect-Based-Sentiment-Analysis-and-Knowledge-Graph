"""
create_neo4j_graph.py
=====================

Import the Neo4j-ready CSV files generated by prepare_kg_data.py.

The same importer works with:
- Local Neo4j: bolt://localhost:7687
- Neo4j AuraDB: neo4j+s://<instance>.databases.neo4j.io

Recommended usage
-----------------
Set connection settings through environment variables:

Windows PowerShell:
    $env:NEO4J_URI="bolt://localhost:7687"
    $env:NEO4J_USERNAME="neo4j"
    $env:NEO4J_PASSWORD="your-password"
    $env:NEO4J_DATABASE="neo4j"

Then run:
    python knowledge_graph/scripts/create_neo4j_graph.py

For Aura later, change only NEO4J_URI / credentials and run the same script.

The importer is idempotent:
- nodes are MERGEd by stable IDs
- relationships are MERGEd by their endpoints
- rerunning updates properties rather than duplicating the graph

Use --clear-existing ONLY when you intentionally want to delete the entire
target database before importing this thesis graph.
"""

