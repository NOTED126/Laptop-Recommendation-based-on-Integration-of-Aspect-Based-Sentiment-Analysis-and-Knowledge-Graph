def clean_text(value):
    """Return a stripped string or None for a missing/blank value."""
    if pd.isna(value):
        return None
    text = str(value).strip()
    if not text or text.lower() in {"nan", "none", "null"}:
        return None
    return text


def slugify(value):
    """Create a deterministic lowercase identifier fragment."""
    text = clean_text(value) or "unknown"
    text = text.lower()
    text = re.sub(r"[^a-z0-9]+", "_", text)
    return text.strip("_")


def stable_id(prefix, *parts):
    """
    Create a readable stable identifier with a short hash suffix.

    The hash prevents collisions when different source strings slugify to the
    same value.
    """
    raw = "||".join(clean_text(p) or "" for p in parts)
    readable = slugify("_".join(clean_text(p) or "" for p in parts))
    digest = hashlib.sha1(raw.encode("utf-8")).hexdigest()[:8]
    readable = readable[:80].rstrip("_")
    return f"{prefix}__{readable}__{digest}"


def extract_bestbuy_product_code(url):
    """
    Extract the Best Buy product code from both standard and open-box URLs.

    Examples:
      /product/<slug>/JJ8V8H3JC2
      /product/<slug>/JJGGLH86J4/sku/6615728/openbox
    """
    url = clean_text(url)
    if not url:
        return None

    parts = [p for p in urlparse(url).path.split("/") if p]

    try:
        product_index = parts.index("product")
    except ValueError:
        return None

    # Best Buy product URLs used by this project have:
    # product / product-slug / product-code
    code_index = product_index + 2
    if code_index < len(parts):
        code = parts[code_index]
        if code:
            return code
    return None


def first_number(value):
    """Extract the first signed/unsigned decimal number from a source string."""
    text = clean_text(value)
    if text is None:
        return None

    match = re.search(r"-?\d+(?:\.\d+)?", text.replace(",", ""))
    if not match:
        return None

    return float(match.group())


def integer_number(value):
    number = first_number(value)
    if number is None:
        return None
    return int(round(number))


def yes_no_bool(value):
    text = clean_text(value)
    if text is None:
        return None

    normalized = text.lower()
    if normalized in {"yes", "true", "1"}:
        return True
    if normalized in {"no", "false", "0"}:
        return False
    return None


def parse_resolution(value):
    """Return (width_px, height_px) from strings such as '2560 x 1600'."""
    text = clean_text(value)
    if text is None:
        return None, None

    match = re.search(r"(\d{3,5})\s*[x×]\s*(\d{3,5})", text, flags=re.I)
    if not match:
        return None, None

    return int(match.group(1)), int(match.group(2))


def csv_safe_dataframe(df):
    """
    Keep pandas output friendly for Neo4j import and CSV inspection.

    Pandas will leave missing scalar values as blank cells in CSV.
    """
    return df.where(pd.notna(df), None)


