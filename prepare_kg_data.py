def load_specifications(specifications_dir):
    specifications_dir = Path(specifications_dir)
    if not specifications_dir.exists():
        raise FileNotFoundError(
            f"Specifications directory does not exist: {specifications_dir}"
        )

    files = sorted(specifications_dir.glob("*.csv"))
    if not files:
        raise FileNotFoundError(
            f"No CSV files found in specifications directory: {specifications_dir}"
        )

    rows = []
    expected_columns = None

    for path in files:
        df = pd.read_csv(path)

        if len(df) != 1:
            raise ValueError(
                f"{path.name} contains {len(df)} rows. "
                "Each specification CSV must contain exactly one laptop."
            )

        current_columns = list(df.columns)

        if expected_columns is None:
            expected_columns = current_columns
        elif current_columns != expected_columns:
            raise ValueError(
                f"Column mismatch in {path.name}. "
                "All specification CSVs must share the same schema."
            )

        row = df.iloc[0].copy()
        row["source_file"] = path.name
        rows.append(row)

    specs = pd.DataFrame(rows).reset_index(drop=True)

    required = [
        "Brand",
        "Model",
        "Product Name",
        "Product URL",
        "Price ($)",
        "Image URL",
        "Processor Brand",
        "Processor Model",
        "Processor Model Number",
        "GPU Brand",
        "Graphics",
    ]

    missing = [column for column in required if column not in specs.columns]
    if missing:
        raise ValueError(f"Missing required specification columns: {missing}")

    if specs["Product Name"].duplicated().any():
        duplicates = specs.loc[
            specs["Product Name"].duplicated(keep=False), "Product Name"
        ].tolist()
        raise ValueError(f"Duplicate Product Name values found: {duplicates}")

    return specs, files


def load_scores(scores_path):
    scores_path = Path(scores_path)
    if not scores_path.exists():
        raise FileNotFoundError(f"Laptop aspect score file not found: {scores_path}")

    scores = pd.read_csv(scores_path)

    required = [
        "laptop",
        "canonical_aspect",
        "canonical_label",
        "positive_reviews",
        "negative_reviews",
        "neutral_reviews",
        "mixed_reviews",
        "reviews_mentioning_aspect",
        "positive_ratio",
        "adjusted_score",
        "evidence_confidence",
        "evidence_level",
        "has_direct_evidence",
    ]

    missing = [column for column in required if column not in scores.columns]
    if missing:
        raise ValueError(f"Missing required score columns: {missing}")

    if scores.duplicated(["laptop", "canonical_aspect"]).any():
        raise ValueError(
            "Duplicate (laptop, canonical_aspect) rows exist in the score file."
        )

    return scores


def validate_laptop_matching(specs, scores):
    specification_names = set(specs["Product Name"].astype(str))
    score_names = set(scores["laptop"].astype(str))

    missing_from_scores = sorted(specification_names - score_names)
    missing_from_specs = sorted(score_names - specification_names)

    if missing_from_scores or missing_from_specs:
        message = ["Laptop names do not match exactly between the two inputs."]

        if missing_from_scores:
            message.append(
                "Present in specifications but missing from scores:\n  - "
                + "\n  - ".join(missing_from_scores)
            )

        if missing_from_specs:
            message.append(
                "Present in scores but missing from specifications:\n  - "
                + "\n  - ".join(missing_from_specs)
            )

        raise ValueError("\n".join(message))


