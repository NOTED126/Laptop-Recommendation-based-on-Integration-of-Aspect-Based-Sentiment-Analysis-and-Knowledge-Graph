def create_laptop_nodes(specs):
    records = []

    for _, row in specs.iterrows():
        product_name = clean_text(row["Product Name"])
        product_url = clean_text(row["Product URL"])
        product_code = extract_bestbuy_product_code(product_url)

        # Use the Best Buy product code when possible. The source product name
        # is included in the identifier input as a collision safeguard.
        if product_code:
            laptop_id = stable_id("laptop", product_code, product_name)
        else:
            laptop_id = stable_id("laptop", product_name)

        resolution_width, resolution_height = parse_resolution(
            row.get("Screen Resolution")
        )

        records.append(
            {
                "laptop_id": laptop_id,
                "bestbuy_product_code": product_code,
                "product_name": product_name,
                "model": clean_text(row.get("Model")),
                "brand_name": clean_text(row.get("Brand")),
                "price_usd": first_number(row.get("Price ($)")),
                "product_url": product_url,
                "image_url": clean_text(row.get("Image URL")),
                "color": clean_text(row.get("Color")),
                "release_year": integer_number(row.get("Year of Release")),

                # Display
                "display_type": clean_text(row.get("Display Type")),
                "screen_type": clean_text(row.get("Screen Type")),
                "screen_size_in": first_number(row.get("Screen Size")),
                "screen_resolution": clean_text(row.get("Screen Resolution")),
                "resolution_width_px": resolution_width,
                "resolution_height_px": resolution_height,
                "touch_screen": yes_no_bool(row.get("Touch Screen")),
                "refresh_rate_hz": first_number(row.get("Refresh Rate")),
                "brightness_nits": first_number(row.get("Brightness")),

                # Memory/storage
                "storage_type": clean_text(row.get("Storage Type")),
                "storage_gb": first_number(row.get("Total Storage Capacity")),
                "ram_gb": first_number(row.get("System Memory (RAM)")),
                "ram_type": clean_text(row.get("Type of Memory (RAM)")),
                "ram_speed_mhz": first_number(row.get("System Memory RAM Speed")),
                "memory_slots": integer_number(row.get("Number Of Memory Slots")),
                "memory_sticks_included": integer_number(
                    row.get("Number of Memory Sticks Included")
                ),

                # GPU / graphics behaviour
                "graphics_type": clean_text(row.get("Graphics Type")),

                # OS detail kept on Laptop because architecture is incomplete in
                # the scraped dataset and can vary independently of the OS node.
                "os_architecture": clean_text(
                    row.get("Operating System Architecture")
                ),

                # Connectivity
                "display_connectors": clean_text(row.get("Display Connector(s)")),
                "thunderbolt_ports": integer_number(
                    row.get("Number of Thunderbolt Ports (Total)")
                ),
                "usb_ports": clean_text(row.get("USB Ports")),
                "usb_c_charging_ports": integer_number(
                    row.get("Number of USB-C Charging Ports")
                ),
                "headphone_jack": yes_no_bool(row.get("Headphone Jack")),
                "microphone_input": yes_no_bool(row.get("Microphone Input")),
                "wireless_connectivity": clean_text(
                    row.get("Wireless Connectivity")
                ),
                "wifi_standard": clean_text(
                    row.get("Wireless Networking Standard")
                ),
                "ethernet_ports": integer_number(
                    row.get("Number Of Ethernet Ports")
                ),

                # Cooling / power / battery
                "cpu_cooling_system": clean_text(row.get("CPU Cooling System")),
                "power_supply_watts": first_number(
                    row.get("Power Supply Maximum Wattage")
                ),
                "battery_life_hours": first_number(row.get("Battery Life (up to)")),

                # Camera / microphone
                "front_camera": yes_no_bool(row.get("Front-Facing Camera")),
                "front_camera_resolution": clean_text(
                    row.get("Front Facing Camera Video Resolution")
                ),
                "built_in_microphone": yes_no_bool(
                    row.get("Built-In Microphone")
                ),

                # Dimensions
                "height_in": first_number(row.get("Product Height")),
                "width_in": first_number(row.get("Product Width")),
                "depth_in": first_number(row.get("Product Depth")),
                "weight_lb": first_number(row.get("Product Weight")),

                # Audit information
                "specification_source_file": clean_text(row.get("source_file")),
            }
        )

    laptops = pd.DataFrame(records)

    if laptops["laptop_id"].duplicated().any():
        raise ValueError("Generated duplicate laptop_id values.")

    return laptops


def create_brand_nodes(specs):
    brands = sorted(
        clean_text(value)
        for value in specs["Brand"].dropna().unique()
        if clean_text(value)
    )

    return pd.DataFrame(
        [
            {
                "brand_id": stable_id("brand", brand),
                "brand_name": brand,
            }
            for brand in brands
        ]
    )


def create_processor_nodes(specs):
    rows = []

    for _, row in specs.iterrows():
        brand = clean_text(row.get("Processor Brand"))
        model = clean_text(row.get("Processor Model"))
        model_number = clean_text(row.get("Processor Model Number"))

        processor_id = stable_id("cpu", brand, model, model_number)

        display_name_parts = []
        for part in [model, model_number]:
            if part and part not in display_name_parts:
                display_name_parts.append(part)

        display_name = " ".join(display_name_parts) or brand

        rows.append(
            {
                "processor_id": processor_id,
                "processor_brand": brand,
                "processor_model": model,
                "processor_model_number": model_number,
                "processor_display_name": display_name,
            }
        )

    return (
        pd.DataFrame(rows)
        .drop_duplicates("processor_id")
        .sort_values("processor_display_name")
        .reset_index(drop=True)
    )


def create_gpu_nodes(specs):
    rows = []

    for _, row in specs.iterrows():
        brand = clean_text(row.get("GPU Brand"))
        graphics_name = clean_text(row.get("Graphics"))
        graphics_type = clean_text(row.get("Graphics Type"))

        gpu_id = stable_id("gpu", brand, graphics_name)

        rows.append(
            {
                "gpu_id": gpu_id,
                "gpu_brand": brand,
                "graphics_name": graphics_name,
                "graphics_type": graphics_type,
            }
        )

    return (
        pd.DataFrame(rows)
        .drop_duplicates("gpu_id")
        .sort_values("graphics_name")
        .reset_index(drop=True)
    )


def create_os_nodes(specs):
    names = sorted(
        clean_text(value)
        for value in specs["Operating System"].dropna().unique()
        if clean_text(value)
    )

    return pd.DataFrame(
        [
            {
                "os_id": stable_id("os", name),
                "os_name": name,
            }
            for name in names
        ]
    )


def create_aspect_nodes(scores):
    rows = []

    for aspect, group in scores.groupby("canonical_aspect", sort=True):
        first = group.iloc[0]

        rows.append(
            {
                "aspect_id": clean_text(aspect),
                "aspect_name": clean_text(first.get("canonical_label")),
                "prior_score": first.get("prior_score"),
                "prior_score_0_100": first.get("prior_score_0_100"),
                "prior_positive_ratio": first.get("prior_positive_ratio"),
                "total_reviews_mentioning_aspect": first.get(
                    "total_reviews_mentioning_aspect"
                ),
                "laptops_with_evidence": first.get("laptops_with_evidence"),
                "prior_strength": first.get("prior_strength"),
                "neutral_weight": first.get("neutral_weight"),
                "mixed_weight": first.get("mixed_weight"),
            }
        )

    return pd.DataFrame(rows)


